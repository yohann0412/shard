import { existsSync, mkdirSync, rmSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { execa } from 'execa';
import { CONFIG_FILE, loadConfig } from '../../src/config/load.js';
import { git } from './checkout.js';
import { cliPath, harnessRoot, recipesDir, reposDir } from './paths.js';
import { say } from './provenance.js';
import { recipeProblems, recipeSchema } from './recipe.js';

const USAGE = 'Usage: node dist/scripts/experiments/new-repo.js <git-url>\n';

/** A recipe name from a repository URL: its last path segment, lowercased, without `.git`. */
function nameFromUrl(url: string): string {
  return path
    .basename(url)
    .replace(/\.git$/, '')
    .toLowerCase()
    .replace(/[^a-z0-9._-]/g, '-');
}

/**
 * Onboards a repository: clones it into work/repos/<name>, runs `isolate init --allow-unmanaged` there, writes a draft
 * recipe (status "draft", pinned to the cloned commit, with the generated config inlined when init succeeded) and
 * prints what a human must still fill in before `just experiment-a <name>`.
 */
async function main(argv: string[]): Promise<number> {
  const url = argv[0];
  if (url === undefined || argv.length > 1) {
    process.stderr.write(USAGE);
    return 2;
  }
  const name = nameFromUrl(url);
  const recipeFile = path.join(recipesDir, `${name}.json`);
  if (existsSync(recipeFile)) throw new Error(`${path.relative(harnessRoot, recipeFile)} already exists; edit it instead`);
  const dir = path.join(reposDir, name);
  rmSync(dir, { recursive: true, force: true });
  mkdirSync(reposDir, { recursive: true });

  say(`cloning ${url} into ${path.relative(harnessRoot, dir)}`);
  await execa('git', ['clone', '--quiet', '--depth', '1', url, dir]);
  const commit = await git(dir, ['rev-parse', 'HEAD']);
  say('isolate init --allow-unmanaged');
  const init = await execa(process.execPath, [cliPath, 'init', '--allow-unmanaged'], { cwd: dir, reject: false, all: true });
  process.stderr.write(`${init.all}\n`);
  const initialized = init.exitCode === 0 && existsSync(path.join(dir, CONFIG_FILE));

  const draft = {
    name,
    source: 'git',
    url,
    commit,
    status: 'draft',
    blocker: null,
    workdir: '.',
    install: [],
    build: [],
    env: {},
    pathPrefix: [],
    playwrightArgs: [],
    baselinePorts: [],
    ...(initialized ? { isolateConfig: await loadConfig(dir) } : {}),
    notes: [initialized ? 'isolateConfig was generated by `isolate init --allow-unmanaged`; review it.' : `isolate init --allow-unmanaged failed (exit code ${init.exitCode}); write isolateConfig by hand.`],
  };
  mkdirSync(recipesDir, { recursive: true });
  writeFileSync(recipeFile, `${JSON.stringify(draft, null, 2)}\n`);

  const todo = recipeProblems(recipeSchema.parse(draft));
  process.stdout.write(`Draft recipe: ${path.relative(harnessRoot, recipeFile)} (${url} at ${commit})

Fill in by hand:
  - install and build: shell lines run as one bash script at the checkout root (the harness clones the repo itself)
  - env, pathPrefix (e.g. a Node or pnpm version the repo needs), workdir (where Playwright runs), baselinePorts
    (the ports the repo's own webServer binds), and playwrightArgs for a subset
${todo.map((problem) => `  - ${problem}`).join('\n')}

Then run:
  just experiment-a ${name}
  just experiment-b ${name}
  just report
`);
  return 0;
}

main(process.argv.slice(2)).then(
  (code) => {
    process.exitCode = code;
  },
  (error: unknown) => {
    say(`failed: ${error instanceof Error ? error.message : String(error)}`);
    process.exitCode = 1;
  },
);
